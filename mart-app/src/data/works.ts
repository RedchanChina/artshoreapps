/**
 * 计算作品所有档位的线上已售总数。
 */
function sumOnlineSold(tiers: EditionTier[]): number {
  return tiers.reduce((sum, t) => sum + t.onlineSoldCount, 0);
}

/**
 * 计算作品所有档位的全球总限量。
 */
function sumTotalEditions(tiers: EditionTier[]): number {
  return tiers.reduce((sum, t) => sum + t.totalEditions, 0);
}

